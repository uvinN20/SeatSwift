res=[]
def check(n, ok, extra=""):
    res.append(ok); print(("PASS " if ok else "FAIL ")+n+(f"   <-- {extra}" if (extra and not ok) else ""))
def api(method, path, body=None, token=None):
    req=urllib.request.Request(API+path, data=json.dumps(body).encode() if body is not None else None, method=method, headers={"Content-Type":"application/json", **({"Authorization":"Bearer "+token} if token else {})})
    try:
        with urllib.request.urlopen(req) as r: return r.status, json.loads(r.read() or b"null")
    except urllib.error.HTTPError as e: return e.code, json.loads(e.read() or b"null")

